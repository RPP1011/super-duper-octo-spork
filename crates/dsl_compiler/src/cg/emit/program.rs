/// Emit the full set of WGSL + Rust source files for a
/// [`ComputeSchedule`].
///
/// Walks every kernel in every stage, lowers each to a `(KernelSpec,
/// body)` pair via Task 4.2's [`kernel_topology_to_spec_and_body`], and
/// composes the WGSL + Rust file contents using the four
/// [`crate::kernel_lowerings::lower_*`] helpers.
///
/// # Errors
///
/// - [`ProgramEmitError::KernelLowering`] — any kernel's spec lowering
///   raised a typed [`KernelEmitError`] (op-id out-of-range, empty
///   topology, inner-walk arena failure, spec-validation failure).
/// - [`ProgramEmitError::KernelNameCollision`] — two kernels in the
///   schedule produced the same snake_case name. (See `# Limitations`
///   on the module-level docs.)
pub fn emit_cg_program(
    schedule: &ComputeSchedule,
    prog: &CgProgram,
) -> Result<EmittedArtifacts, ProgramEmitError> {
    emit_cg_program_with_debug(schedule, prog, crate::cg::lower::DebugDepth::Off)
}

/// Same as [`emit_cg_program`] but threads the compiler-debug-mode
/// level through to `synthesize_dispatch`, which gates the emitted
/// `DebugTimings` / `MemDelta` / `KERNEL_DSL_SOURCE_MAP` surface.
///
/// Per-fixture build.rs scripts that want per-kernel attribution
/// invoke this directly; everything else routes through
/// `emit_cg_program` (`DebugDepth::Off`).
pub fn emit_cg_program_with_debug(
    schedule: &ComputeSchedule,
    prog: &CgProgram,
    debug: crate::cg::lower::DebugDepth,
) -> Result<EmittedArtifacts, ProgramEmitError> {
    let mut wgsl_files: BTreeMap<String, String> = BTreeMap::new();
    let mut rust_files: BTreeMap<String, String> = BTreeMap::new();
    let mut kernel_index: Vec<String> = Vec::new();
    let mut kernel_specs: Vec<crate::kernel_binding_ir::KernelSpec> = Vec::new();
    let mut seen_names: BTreeMap<String, (usize, usize)> = BTreeMap::new();

    let ctx = EmitCtx {
        prog,
        naming: HandleNamingStrategy::Structural,
        tile_walk_index: std::cell::RefCell::new(None),
        rng_loop_iter_var: std::cell::RefCell::new(None),
        tables_referenced: std::cell::RefCell::new(
            std::collections::BTreeSet::new(),
        ),
        dispatch: std::cell::Cell::new(None),
        view_target_locals: std::cell::RefCell::new(Vec::new()),
        pending_target_lets: std::cell::RefCell::new(Vec::new()),
        bound_target_exprs: std::cell::RefCell::new(std::collections::HashSet::new()),
        event_ring_atomic_loads: std::cell::Cell::new(false),
        alive_atomic_writes: std::cell::Cell::new(false),
        // f32 RMW: per-kernel bitset of upgraded f32 SoA fields. Set
        // by the kernel emit before each kernel's body emit; restored
        // on exit. Default 0 (no upgrades) preserves the existing
        // per-stmt emit shape verbatim.
        f32_atomic_field_writes: std::cell::Cell::new(0),
        // f32 RMW: set of LocalIds whose Let stmt should emit as
        // `local_N = V;` (assignment to a var declared above the
        // active CAS loop). Populated only inside
        // `lower_cg_stmt_list_to_wgsl` for the duration of a CAS-loop
        // body emit; restored on exit.
        var_promoted_locals: std::cell::RefCell::new(std::collections::HashSet::new()),
        // 2026-05-09 (Compiler debug mode Phase 2): mirror the
        // program-level WGSL instrumentation bitset onto the emit
        // context. Default `DebugWgslFlags::NONE` preserves the
        // existing emit shape; per-runtime build.rs opt-in via
        // `LowerOpts.debug_wgsl` flows through `CgProgram.debug_wgsl`.
        debug_wgsl: prog.debug_wgsl,
        // Post-CAS emit gating: the f32 first-writer-wins gate.
        // Default `None` keeps the existing CAS-loop shape verbatim;
        // the `If`-arm of the per-stmt emit toggles it for the inner
        // Assign whose `(field, target)` is also read by the outer
        // cond.
        f32_first_writer_gate: std::cell::Cell::new(None),
        producer_kernel_ids: assign_producer_kernel_ids(schedule, prog),
        current_kernel_index: std::cell::Cell::new(None),
        intra_emit_idx: std::cell::Cell::new(0),
        // Enable serial PerAgent scan for f32+Add ViewFold kernels when the
        // program contains at least one such fold.  Each agent slot gets its
        // own thread that accumulates events locally then writes once — no
        // CAS retry loop, no cross-thread contention on view_storage_primary.
        serial_f32_fold: std::cell::Cell::new(has_f32_add_view_fold(prog)),
        in_serial_fold_body: std::cell::Cell::new(false),
        // Self-write + cross-read hazard: per-kernel field set, set by
        // `kernel_topology_to_spec_and_body` before each kernel's body
        // emit and restored on exit. Default empty preserves the
        // existing direct `agent_<field>` read shape verbatim.
        hazard_shadow_fields: std::cell::RefCell::new(std::collections::BTreeSet::new()),
        // Claim-CAS: per-kernel u32/bool field set, set by
        // `kernel_topology_to_spec_and_body` before each kernel's body
        // emit and restored on exit. Default empty preserves the
        // existing plain check-then-set shape verbatim.
        claim_cas_fields: std::cell::RefCell::new(std::collections::BTreeSet::new()),
    };

    for (stage_idx, stage) in schedule.stages.iter().enumerate() {
        for (kernel_idx, topology) in stage.kernels.iter().enumerate() {
            // Set current kernel index before body emit so lower_emit_to_wgsl
            // can resolve the producer_kernel_id. Reset intra_emit_idx to 0 for
            // each kernel (each kernel's emits get their own 0-based idx).
            let ki = KernelIndex { stage: stage_idx, kernel: kernel_idx };
            ctx.current_kernel_index.set(Some(ki));
            ctx.intra_emit_idx.set(0);
            let (spec, body) = kernel_topology_to_spec_and_body(topology, prog, &ctx).map_err(
                |error| ProgramEmitError::KernelLowering {
                    stage_index: stage_idx,
                    kernel_index: kernel_idx,
                    error,
                },
            )?;
            ctx.current_kernel_index.set(None);

            if let Some(prior) = seen_names.get(&spec.name) {
                return Err(ProgramEmitError::KernelNameCollision {
                    name: spec.name.clone(),
                    first_at: *prior,
                    second_at: (stage_idx, kernel_idx),
                });
            }
            seen_names.insert(spec.name.clone(), (stage_idx, kernel_idx));

            // PerEvent kernels whose body contains a post-CAS emit gate
            // (`_f32_cas_did_transition_`) suffer a CAS race: multiple
            // threads competing on the same target slot produce non-
            // deterministic Ignited event sequences across runs.  The
            // fix: collapse the dispatch to a single-thread sequential
            // scan over all events.  Detection uses the gate variable's
            // name-prefix as a body substring — the emit path for
            // `f32_first_writer_gate` always declares this prefix.
            let sequential_per_event =
                matches!(topology, KernelTopology::Indirect { .. })
                && body.contains("_f32_cas_did_transition_");

            let wgsl = compose_wgsl_file(&spec, &body, topology, prog, sequential_per_event);
            wgsl_files.insert(format!("{}.wgsl", spec.name), wgsl);

            let rs = compose_rust_module_file(&spec, topology, sequential_per_event);
            rust_files.insert(format!("{}.rs", spec.name), rs);

            kernel_index.push(spec.name.clone());
            kernel_specs.push(spec);
        }
    }

    // Synthesize lib.rs (per-kernel `pub mod` declarations only;
    // Kernel trait + bgl helpers now live in `engine::gpu` —
    // hand-written platform infrastructure, not compiler-emitted).
    rust_files.insert("lib.rs".to_string(), synthesize_lib_rs(&kernel_index));

    // Synthesize the per-fixture cross-cutting modules. Each becomes
    // a `<name>.rs` entry under `<crate>/src/generated/`; lib.rs
    // declares each via `pub mod <name>;`.
    //
    // Phase 7 boids GPU pipeline (2026-05-02): dropped the wolf-sim-
    // shaped runtime container synthesizers — `binding_sources`,
    // `resident_context`, `external_buffers`, `transient_handles`,
    // `pingpong_context`, `pool`. Per-fixture runtime crates own
    // their own buffers and construct each kernel's `Bindings`
    // directly with explicit `&wgpu::Buffer` refs; the deleted
    // containers were a wolf-sim-runtime-specific aggregation pattern
    // that doesn't fit per-field-buffer fixtures like boids.
    rust_files.insert(
        "schedule.rs".to_string(),
        super::cross_cutting::synthesize_schedule(schedule, prog),
    );
    // Build the optional .sim source-loc map (D4 only). For Phase 1
    // we surface the source span of the originating physics rule /
    // mask / view (whichever the kernel ultimately lowers from). The
    // emit walks `kernel_index` in order, asks the topology for its
    // primary op id, and reads `prog.ops[op].span`. Kernels with no
    // single-op origin (e.g. fused multi-op chronicle dispatchers)
    // surface as a sentinel `("", 0, 0)` — the runtime treats
    // missing entries as "compiler couldn't trace this kernel back
    // to a single .sim span" without panicking.
    let dsl_source_map = if debug.emits_source_map() {
        build_dsl_source_map(schedule, prog, &kernel_index)
    } else {
        Vec::new()
    };
    rust_files.insert(
        "dispatch.rs".to_string(),
        super::cross_cutting::synthesize_dispatch_with_debug(
            &kernel_index,
            debug,
            &dsl_source_map,
        ),
    );

    Ok(EmittedArtifacts {
        wgsl_files,
        rust_files,
        kernel_index,
        kernel_specs,
    })
}

/// Build the D4 source-map vec — one `(kernel_name, file, line_start,
/// line_end)` entry per kernel in `kernel_index`. The current Span IR
/// only carries byte offsets (no file path, no line numbers), so for
/// Phase 1 we surface the `(byte_start, byte_end)` of the originating
/// op's span in the `line_start` / `line_end` slots and stamp the
/// file as `(unknown).sim` (the schedule doesn't pin the source file
/// today). Per-fixture build.rs scripts that want the real `.sim`
/// path can post-process the emitted dispatch.rs via a
/// `KERNEL_DSL_SOURCE_MAP_OVERRIDE` const — left to a follow-up.
///
/// Kernels with multiple originating ops surface the FIRST op's span
/// (consistent with the schedule's classify-on-first-op convention).
/// Kernels with no resolvable op (`Indirect.consumers` for
/// example) emit the producer op's span.
fn build_dsl_source_map(
    schedule: &ComputeSchedule,
    prog: &CgProgram,
    kernel_index: &[String],
) -> Vec<(String, String, u32, u32)> {
    use crate::cg::schedule::synthesis::KernelTopology;
    // Walk the schedule in the same order kernel_index was built so
    // each `kernel_index[i]` lines up with the i'th visited topology.
    let mut entries: Vec<(String, String, u32, u32)> =
        Vec::with_capacity(kernel_index.len());
    let mut idx = 0usize;
    for stage in &schedule.stages {
        for topology in &stage.kernels {
            if idx >= kernel_index.len() {
                break;
            }
            let primary_op = match topology {
                KernelTopology::Fused { ops, .. } => ops.first().copied(),
                KernelTopology::Split { op, .. } => Some(*op),
                KernelTopology::Indirect { producer, .. } => Some(*producer),
            };
            let (start, end) = primary_op
                .and_then(|op_id| prog.ops.get(op_id.0 as usize).map(|op| op.span))
                .map(|s| (s.start as u32, s.end as u32))
                .unwrap_or((0, 0));
            entries.push((
                kernel_index[idx].clone(),
                "(unknown).sim".to_string(),
                start,
                end,
            ));
            idx += 1;
        }
    }
    entries
}

