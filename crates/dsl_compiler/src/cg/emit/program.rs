fn classify_binding(name: &str) -> BindingSource<'_> {
    if name == "event_ring" {
        return BindingSource::EventRingRing;
    }
    if name == "event_tail" {
        return BindingSource::EventRingTail;
    }
    if name == "cfg" {
        return BindingSource::Cfg;
    }
    if name == "voxel_grid" {
        return BindingSource::VoxelGrid;
    }
    if name == "navgrid" {
        return BindingSource::Navgrid;
    }
    if name == "navgrid_cfg" {
        return BindingSource::NavgridCfg;
    }
    if let Some(col) = name.strip_prefix("ability_registry_") {
        return BindingSource::Registry(col);
    }
    if let Some(col) = name.strip_prefix("agent_") {
        if STANDARD_AGENT_COLUMNS.contains(&col) {
            return BindingSource::AgentBuffer(col);
        }
    }
    BindingSource::Extras
}

/// Render the Rust expression that yields the `&'a wgpu::Buffer` for
/// a binding classified through [`classify_binding`]. `name` is the
/// emitted Bindings field name (used for the extras-arm getter and for
/// the AgentBuffer's `.expect()` message).
fn render_from_context_expr(src: &BindingSource<'_>, name: &str) -> String {
    match src {
        BindingSource::EventRingRing => "ctx.event_ring.ring()".to_string(),
        BindingSource::EventRingTail => "ctx.event_ring.tail()".to_string(),
        BindingSource::AgentBuffer(col) => format!(
            "ctx.state.{col}_buf.expect(\"kernel binds agent_{col} but the runtime didn't supply ctx.state.{col}_buf\")"
        ),
        BindingSource::Registry(col) => format!("&ctx.registry.{col}"),
        BindingSource::VoxelGrid => "ctx.voxel_grid.expect(\"kernel binds voxel_grid but the runtime didn't supply ctx.voxel_grid\")".to_string(),
        BindingSource::Navgrid => "ctx.navgrid.expect(\"kernel binds navgrid but the runtime didn't supply ctx.navgrid\")".to_string(),
        BindingSource::NavgridCfg => "ctx.navgrid_cfg.expect(\"kernel binds navgrid_cfg but the runtime didn't supply ctx.navgrid_cfg\")".to_string(),
        BindingSource::Cfg => "extras.cfg.clone()".to_string(),
        BindingSource::Extras => {
            if crate::kernel_binding_ir::is_mask_bitmap_binding(name) {
                format!("extras.{name}.clone()")
            } else {
                format!("extras.{name}")
            }
        }
    }
}

/// Compose the `from_context(ctx)` (or `from_context_with_extras(ctx,
/// extras)` plus sibling `<Pascal>Extras` struct) impl block for a
/// generic-kernel Bindings struct.
///
/// Walks the spec's bindings, classifies each via [`classify_binding`],
/// and emits:
///
/// - When every binding routes through shared sources (state /
///   event_ring / registry): a parameterless `from_context(ctx)` impl.
/// - Otherwise (at least one binding falls through to extras OR a
///   `cfg` binding exists — cfg always rides on extras since cfg
///   buffers are per-fixture): a `<Pascal>Extras<'a>` struct holding
///   the unclassified fields + a `from_context_with_extras(ctx, extras)`
///   impl.
///
/// The Cfg binding is treated as "extras" because the cfg buffer is
/// always a per-fixture per-kernel buffer the runtime owns and writes
/// each tick. Routing it through extras keeps the constructor's
/// shared-context narrow (no per-kernel cfg fanout in the context
/// type).
fn compose_bindings_from_context(spec: &KernelSpec) -> String {
    // AliasOf bindings have no struct field (handled at BindGroupEntry
    // time in lower_rust_bg_entries).
    let classified: Vec<(&str, BindingSource<'_>)> = spec
        .bindings
        .iter()
        .filter(|b| !matches!(b.bg_source, BgSource::AliasOf(_)))
        .map(|b| (b.name.as_str(), classify_binding(&b.name)))
        .collect();

    let needs_extras = classified
        .iter()
        .any(|(_, src)| matches!(src, BindingSource::Cfg | BindingSource::Extras));

    let pascal = &spec.pascal;
    let mut out = String::new();

    if needs_extras {
        writeln!(out, "pub struct {pascal}Extras<'a> {{").expect("write");
        for (name, src) in classified
            .iter()
            .filter(|(_, src)| matches!(src, BindingSource::Cfg | BindingSource::Extras))
        {
            if matches!(src, BindingSource::Cfg)
                || crate::kernel_binding_ir::is_mask_bitmap_binding(name)
            {
                // PERF (2026-09-03): every kernel's cfg block lives in ONE
                // runtime-owned uniform buffer at a 256-byte stride, written
                // once per tick; the binding is a slice of it.
                writeln!(out, "    pub {name}: wgpu::BufferBinding<'a>,").expect("write");
            } else {
                writeln!(out, "    pub {name}: &'a wgpu::Buffer,").expect("write");
            }
        }
        out.push_str("}\n\n");
    }

    writeln!(out, "impl<'a> {pascal}Bindings<'a> {{").expect("write");
    out.push_str("    /// Construct from the shared [`engine::gpu::KernelBindingsContext`].\n");
    if needs_extras {
        writeln!(
            out,
            "    /// + per-kernel [`{pascal}Extras`] supplying fixture-specific buffers."
        )
        .expect("write");
    }
    out.push_str(
        "    ///\n    \
         /// Compiler-emitted; see the naming convention in\n    \
         /// [`engine::gpu::bindings_context`].\n",
    );
    if needs_extras {
        writeln!(
            out,
            "    pub fn from_context_with_extras(\n        \
                 ctx: &engine::gpu::KernelBindingsContext<'a>,\n        \
                 extras: &{pascal}Extras<'a>,\n    ) -> Self {{"
        )
        .expect("write");
    } else {
        out.push_str(
            "    pub fn from_context(\n        \
             ctx: &engine::gpu::KernelBindingsContext<'a>,\n    ) -> Self {\n",
        );
    }
    out.push_str("        Self {\n");
    for (name, src) in &classified {
        let expr = render_from_context_expr(src, name);
        writeln!(out, "            {name}: {expr},").expect("write");
    }
    out.push_str("        }\n    }\n}\n\n");

    out
}

/// Compose the `impl engine::gpu::Kernel for <Pascal>Kernel { … }`
/// block. The trait carries the minimum surface every kernel
/// implements: `new` (compile shader + build pipeline) + `record`
/// (encode dispatch). Per-kernel `build_cfg` and `bind` methods are
/// gone — `Cfg` is a `#[repr(C)]` POD that callers construct
/// directly, and `Bindings` is a typed struct wired inline at the
/// dispatch call site with explicit `&wgpu::Buffer` refs.
fn compose_kernel_trait_impl(spec: &KernelSpec, topology: &KernelTopology, sequential_per_event: bool) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "impl engine::gpu::Kernel for {pascal}Kernel {{\n    \
         type Bindings<'a> = {pascal}Bindings<'a>;\n    \
         type Cfg = {cfg};\n\n",
        pascal = spec.pascal,
        cfg = spec.cfg_struct
    ));

    // new()
    out.push_str("    fn new(device: &wgpu::Device) -> Self {\n");
    out.push_str(&format!(
        "        let shader = device.create_shader_module(wgpu::ShaderModuleDescriptor {{\n            \
             label: Some(\"engine_gpu_rules::{name}::wgsl\"),\n            \
             source: wgpu::ShaderSource::Wgsl(SHADER_SRC.into()),\n        \
             }});\n",
        name = spec.name
    ));
    out.push_str(&format!(
        "        let bgl = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {{\n            \
             label: Some(\"engine_gpu_rules::{name}::bgl\"),\n            \
             entries: &[\n",
        name = spec.name
    ));
    out.push_str(&render_cg_bgl_entries(spec));
    out.push_str("            ],\n        });\n");
    out.push_str(&format!(
        "        let pl = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {{\n            \
             label: Some(\"engine_gpu_rules::{name}::pl\"),\n            \
             bind_group_layouts: &[&bgl],\n            \
             push_constant_ranges: &[],\n        \
             }});\n",
        name = spec.name
    ));
    out.push_str(&format!(
        "        let pipeline = device.create_compute_pipeline(&wgpu::ComputePipelineDescriptor {{\n            \
             label: Some(\"engine_gpu_rules::{name}::pipeline\"),\n            \
             layout: Some(&pl),\n            \
             module: &shader,\n            \
             entry_point: Some(\"{entry}\"),\n            \
             compilation_options: Default::default(),\n            \
             cache: None,\n        \
             }});\n        \
             Self {{ pipeline, bgl, bg_cache: std::cell::RefCell::new(None) }}\n    }}\n\n",
        name = spec.name,
        entry = spec.entry_point
    ));

    // build_cfg + bind dropped from the trait — see compose_kernel_trait_impl
    // doc. `Cfg` is `#[repr(C)]` POD (caller constructs directly);
    // `Bindings` wired inline at dispatch with explicit buffer refs.

    // record()
    if matches!(spec.kind, KernelKind::ViewFold) {
        out.push_str(&compose_view_fold_record_method(spec));
    } else {
        // OneShot dispatch (and sequential per-event) resolve to
        // `pass.dispatch_workgroups(1, 1, 1)` and never reference
        // `agent_cap` — emit the parameter as `_agent_cap` so the
        // synthesized kernel module compiles under `-D unused-
        // variables`. PerAgent / PerEvent / PerPair / PerWord all
        // derive workgroup count from `agent_cap`. Mirrors the legacy
        // `seed_indirect.rs` convention.
        let cap_param = if dispatch_is_one_shot(topology) || sequential_per_event {
            "_agent_cap"
        } else {
            "agent_cap"
        };
        out.push_str(&format!(
            "    fn record(&self, device: &wgpu::Device, encoder: &mut wgpu::CommandEncoder, bindings: &{pascal}Bindings<'_>, {cap_param}: u32) {{\n",
            pascal = spec.pascal,
            cap_param = cap_param,
        ));
        out.push_str("        let entries = [\n");
        out.push_str(&lower_rust_bg_entries(spec));
        out.push_str("        ];\n");
        out.push_str(&format!(
            "        let mut bg_cache = self.bg_cache.borrow_mut();\n        \
                 let bg = engine::gpu::cached_bind_group(&mut bg_cache, device, \"engine_gpu_rules::{name}::bg\", &self.bgl, &entries);\n",
            name = spec.name
        ));
        out.push_str(&format!(
            "        let mut pass = encoder.begin_compute_pass(&wgpu::ComputePassDescriptor {{\n            \
                 label: Some(\"engine_gpu_rules::{name}::pass\"),\n            \
                 timestamp_writes: None,\n        \
                 }});\n",
            name = spec.name
        ));
        out.push_str("        pass.set_pipeline(&self.pipeline);\n");
        out.push_str("        pass.set_bind_group(0, bg, &[]);\n");
        // Sequential per-event kernels dispatch as OneShot (1,1,1): the
        // WGSL body's single thread walks the whole event ring.
        let dispatch_line = if sequential_per_event {
            "        pass.dispatch_workgroups(1, 1, 1);\n".to_string()
        } else {
            compose_dispatch_call(topology, spec)
        };
        out.push_str(&dispatch_line);
        out.push_str("    }\n");
    }

    out.push_str("}\n");
    out
}

/// Render the BGL entries for a CG-emitted kernel, routing through the
/// CG-side helpers `engine::gpu::bgl_storage` / `engine::gpu::bgl_uniform` defined
/// in the synthesized `lib.rs`. Distinct from
/// [`crate::kernel_lowerings::lower_rust_bgl_entries`] which routes
/// through the legacy `crate::fused_mask::bgl_*` path; the legacy
/// path requires the legacy `fused_mask.rs` to define the helpers,
/// which a CG-only output never carries.
fn render_cg_bgl_entries(spec: &KernelSpec) -> String {
    let mut out = String::new();
    for b in &spec.bindings {
        let descriptor = match b.access {
            AccessMode::ReadStorage => format!("engine::gpu::bgl_storage({}, true)", b.slot),
            AccessMode::ReadWriteStorage | AccessMode::AtomicStorage => {
                format!("engine::gpu::bgl_storage({}, false)", b.slot)
            }
            AccessMode::Uniform => format!("engine::gpu::bgl_uniform({})", b.slot),
        };
        writeln!(out, "                {}, // {}", descriptor, b.name)
            .expect("write to String never fails");
    }
    out
}

/// Render the `bindings: <field>: <expr>,` rows for the `bind()`
/// initializer body.
#[allow(dead_code)]
fn compose_bind_body(spec: &KernelSpec) -> String {
    let mut out = String::new();
    for b in &spec.bindings {
        // AliasOf bindings don't have their own struct field; the alias
        // is handled in `lower_rust_bg_entries` at BindGroupEntry time.
        if matches!(b.bg_source, BgSource::AliasOf(_)) {
            continue;
        }
        let value = render_bg_source_expr(&b.bg_source, &b.name);
        out.push_str(&format!("            {field}: {value},\n", field = b.name, value = value));
    }
    out
}

/// Render a [`BgSource`] as the Rust expression that yields the
/// `&'a wgpu::Buffer` used by the `bind()` initializer.
///
/// `field` is the binding's name — used to surface a self-referential
/// fallback for ViewHandle (the generic CG path; today no kernel emits
/// it, so the helper stays defensive).
#[allow(dead_code)]
fn render_bg_source_expr(src: &BgSource, field: &str) -> String {
    match src {
        // `ResidentPathContext` fields are owned `wgpu::Buffer`s (not
        // references). Borrow at the use-site so the synthesized
        // `Bindings { ... }` initializer matches the `&'a wgpu::Buffer`
        // field type. The legacy ViewFold emit path bypasses this
        // helper for its event_ring/event_tail bindings (it constructs
        // the borrow inline at `compose_view_fold_bindings_init`).
        BgSource::Resident(f) => format!("&sources.resident.{f}"),
        BgSource::Transient(f) => format!("sources.transient.{f}"),
        BgSource::External(f) => format!("sources.external.{f}"),
        // `Pool` fields are owned `wgpu::Buffer`s (not references) on
        // the runtime `Pool` struct, unlike `TransientHandles` whose
        // fields are `&'a wgpu::Buffer`. Borrow at the use-site so
        // the synthesized `Bindings { ... }` initializer matches the
        // `&'a wgpu::Buffer` field type.
        BgSource::Pool(f) => format!("&sources.pool.{f}"),
        BgSource::Cfg => "cfg".to_string(),
        BgSource::ViewHandle { accessor, tuple_idx } => {
            // Defensive: until Task 5.4 wires fold-view tuple
            // destructuring at the kernel-module emit layer, the
            // generic path renders a `<accessor>().<idx>`-style
            // expression. The legacy fold kernels destructure into
            // (primary, anchor, ids) locals; today no CG kernel emits
            // ViewHandle — this arm exists so the composer never falls
            // through to a panic if a future spec does.
            format!(
                "sources.resident.{accessor}().{idx} /* {field} */",
                accessor = accessor,
                idx = tuple_idx
            )
        }
        BgSource::AliasOf(target) => {
            // Defensive — AliasOf bindings are filtered out before this
            // helper is called. If a caller skipped the filter, render
            // a self-evidently routable expression rather than panic.
            format!("/* alias of {target} */ sources.external.sim_cfg")
        }
    }
}

