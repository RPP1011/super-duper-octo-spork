/// Compose a single `.wgsl` file from a [`KernelSpec`] + body string +
/// originating [`KernelTopology`] (used to derive the workgroup size).
///
/// The output mirrors the legacy WGSL files' shape:
/// 1. A `// GENERATED ...` header comment.
/// 2. The `@group(0) @binding(N)` declaration block from
///    [`lower_wgsl_bindings`].
/// 3. The `@compute @workgroup_size(N)` annotation, derived from the
///    topology's [`DispatchShape::workgroup_size`].
/// 4. The entry-point function with its `gid` argument and the body
///    from Task 4.2.
///
/// `sequential_per_event`: when `true`, the kernel is a post-CAS-emit
/// PerEvent kernel that must run sequentially to avoid CAS races. The
/// `@workgroup_size` is forced to `1` and the body's `let event_idx =
/// gid.x; if ... { return; }` preamble is replaced with a single-
/// thread guard + a sequential `for` loop over all events.
fn compose_wgsl_file(
    spec: &KernelSpec,
    body: &str,
    topology: &KernelTopology,
    prog: &CgProgram,
    sequential_per_event: bool,
) -> String {
    let mut out = String::new();
    out.push_str("// GENERATED by dsl_compiler — do not edit by hand.\n");
    out.push_str("// Regenerated by each runtime crate's build.rs on cargo check / build.\n");
    out.push('\n');

    // The cfg uniform is referenced by name (e.g. `cfg: MaskHoldCfg`),
    // so the WGSL must declare the matching struct inline before the
    // uniform binding. Shape mirrors the Rust cfg_struct_decl:
    //   ViewFold:  { event_count, tick, second_key_pop, agent_cap }
    //   Generic:   { agent_cap, tick, seed, _pad }
    // (WGSL doesn't accept `[u32; N]` array members in uniforms the way
    // Rust does; the fields are individual u32 scalars.)
    out.push_str(&compose_wgsl_cfg_struct(spec));
    out.push('\n');

    out.push_str(&lower_wgsl_bindings(spec));
    out.push('\n');

    // Emit `const config_<id>: <ty> = <value>;` for every config-const
    // referenced in the kernel body. The substring scan keys on
    // `config_<id>` (the WGSL identifier `lower_cg_expr_to_wgsl`
    // produces for `CgExpr::Read(DataHandle::ConfigConst { id })`).
    // The [`ConfigConstValue`] variant pins the WGSL scalar type:
    // a `u32`-declared config field emits as `5u` and types the const
    // as `u32`, so it can flow into a `u32` ring slot (atomicStore /
    // atomicAdd / atomicOr) without crashing the WGSL validator with
    // an `f32 → u32` auto-conversion error. Non-numeric defaults
    // (Bool / String) skip silently because no kernel references
    // them. Sorted by id for deterministic output.
    //
    // Plan G tunable cfg — runtime-tunable consts (those flagged in
    // `prog.runtime_config_consts`) are NOT emitted as inline `const`
    // declarations. The kernel body's `config_<id>` substring was
    // already rewritten to `cfg.config_<block>_<field>` by the kernel
    // emit (`cg::emit::kernel`), so the body no longer references the
    // bare `config_<id>` token; emitting a const here would dead-code
    // the declaration. Skipping aligns the emit with the per-kernel
    // cfg-uniform field surface.
    let mut emitted_consts = false;
    for (id, value) in &prog.config_const_values {
        if prog.runtime_config_consts.contains(id) {
            continue;
        }
        let needle = format!("config_{}", id);
        if body.contains(&needle) {
            out.push_str(&format!(
                "const config_{}: {} = {};\n",
                id,
                value.wgsl_scalar_ty(),
                value.wgsl_literal()
            ));
            emitted_consts = true;
        }
    }
    if emitted_consts {
        out.push('\n');
    }

    // Static lookup tables — `table <name>: u32[N] = […]`. For each
    // registered table referenced by the kernel body (substring scan
    // for `<name>[`), emit a module-level
    // `const <name>: array<u32, N> = array<u32, N>(v0, v1, …);`
    // declaration. The body's `<name>[<idx>]` expression then indexes
    // the const. Same scan-based pattern as `config_<id>` above; the
    // WGSL validator pins array length match at parse time, so a
    // miss here would surface as a parse error, not a silent bug.
    let mut emitted_tables = false;
    for (name, values) in &prog.tables {
        let needle = format!("{name}[");
        if !body.contains(&needle) {
            continue;
        }
        let n = values.len();
        let init = values
            .iter()
            .map(|v| format!("{v}u"))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "const {name}: array<u32, {n}> = array<u32, {n}>({init});\n"
        ));
        emitted_tables = true;
    }
    if emitted_tables {
        out.push('\n');
    }

    // Spatial-grid prelude: constants + pos_to_cell / cell_index
    // helpers, emitted only when the body touches a spatial binding.
    // The same constants are mirrored on the runtime side
    // (`crate::cg::emit::spatial::{CELL_SIZE,WORLD_HALF_EXTENT,...}`)
    // so per-fixture runtime crates can size matching wgpu buffers
    // without re-deriving the values from the WGSL.
    let spatial_prelude = super::spatial::compose_spatial_prelude(body);
    if !spatial_prelude.is_empty() {
        out.push_str(&spatial_prelude);
    }

    // Emit B1-stub prelude functions for every namespace method whose
    // WGSL function name appears in this kernel's body. The registry
    // (`prog.namespace_registry`) is the source of truth for both the
    // function name (used for the substring scan) and the stub body
    // (emitted verbatim). Walk-and-collect rather than emit-all so the
    // generated WGSL stays minimal and the kernel-by-kernel diff is
    // legible. See `populate_namespace_registry` in `lower::driver`
    // for the registered methods.
    let prelude = compose_namespace_prelude(body, prog);
    if !prelude.is_empty() {
        out.push_str(&prelude);
        out.push('\n');
    }

    // Plan G G3f-deep (audit task #288) — view-storage cross-kernel
    // read prelude. Scoring kernels that reference `view_<id>_get(`
    // get a helper function definition that reads from the
    // corresponding `view_storage_<view_name>_primary` binding (added
    // to the kernel spec by `kernel_topology_to_spec_and_body`'s
    // body-scan step). The MVP: f32 per-agent scalar read with
    // bitcast<f32>. Struct-payload + ring views need a richer prelude
    // (per-cell walk, aggregation) — deferred to the struct-walk
    // follow-up that closes ThreatsNearest / ThreatsDirAwayFromNearest.
    let view_prelude = compose_view_storage_prelude(body, prog);
    if !view_prelude.is_empty() {
        out.push_str(&view_prelude);
        out.push('\n');
    }

    // Plan H slice 3 — ability registry telegraph helpers. Independent
    // from the view-storage helpers (different storage shape, different
    // BGL bindings) so kept in a sibling composer.
    let telegraph_prelude = compose_ability_telegraph_prelude(body);
    if !telegraph_prelude.is_empty() {
        out.push_str(&telegraph_prelude);
        out.push('\n');
    }

    // Emit the deterministic per-agent RNG primitive iff the kernel
    // body references it. Substring-keyed on `per_agent_u32(` so a
    // comment that incidentally names the function doesn't trigger
    // the emit. Body source is `RNG_WGSL_PRELUDE` — the WGSL mirror of
    // `engine::rng::per_agent_u32_pcg` (host-side parity helper). Both
    // sides are pure-Rust / pure-WGSL implementations of the same
    // PCG-XSH-RR mixing chain over the (seed, agent_id, tick,
    // purpose_id) tuple, so the cross-backend stream is bit-equal
    // under shared inputs (P11). See stochastic_probe Gap #2 close
    // (2026-05-04).
    if body.contains("per_agent_u32(") || body.contains("per_agent_u32_with_extra(") {
        out.push_str(RNG_WGSL_PRELUDE);
        out.push('\n');
    }

    // Spatial-stdlib prelude: emit `planar_distance` / `z_separation`
    // helpers when the body references either by call form. Substring
    // gate mirrors the RNG prelude pattern above (a comment naming
    // either function won't trigger the emit because the trailing `(`
    // is required). Closes Gap #B from stdlib_math_probe (2026-05-04).
    if body.contains("planar_distance(") || body.contains("z_separation(") {
        out.push_str(SPATIAL_BUILTIN_WGSL_PRELUDE);
        out.push('\n');
    }

    // Math-stdlib prelude: emit suffixed min/max/clamp wrappers when
    // the body calls any of them. Substring gate per call form
    // (trailing `(`). Closes task #84 surfaced by duel_abilities's
    // attempted shield absorption (2026-05-04).
    if body.contains("min_f32(")  || body.contains("max_f32(")
        || body.contains("min_u32(")  || body.contains("max_u32(")
        || body.contains("min_i32(")  || body.contains("max_i32(")
        || body.contains("clamp_f32(") || body.contains("clamp_u32(")
        || body.contains("clamp_i32(")
    {
        out.push_str(STDLIB_MATH_WGSL_PRELUDE);
        out.push('\n');
    }

    // Voxel-mirror prelude (Phase C + D): emit the `voxel_at` /
    // `voxel_height_at` / `voxel_walkable` / `voxel_line_of_sight`
    // helpers when the kernel body references any of them. Phase D's
    // `terrain.*` lowering uses the namespace-prelude pass to inject
    // `terrain_<method>(...)` wrappers (added to `compose_namespace_prelude`
    // BEFORE this gate), and those wrappers in turn call the helpers
    // below — so we substring-check the wrapper-internal symbols too.
    // The helpers reference the module-scope `voxel_grid` storage
    // binding directly (no pointer args).
    let needs_voxel_helpers = ["voxel_at(", "voxel_height_at(", "voxel_walkable(", "voxel_line_of_sight("]
        .iter()
        .any(|needle| body.contains(needle) || prelude.contains(needle));
    if needs_voxel_helpers {
        out.push_str(VOXEL_GRID_WGSL_PRELUDE);
        out.push('\n');
    }

    // Voxel-region-indices Phase 4b — navgrid helper prelude. Inject
    // when the body or any namespace stub references
    // `voxel_navgrid_walkable(`. Mirrors the voxel-grid pattern but
    // reads a separate `navgrid` storage buffer + a 4-u32 uniform
    // `navgrid_cfg = [size_x, size_z, origin_x, origin_z]`. The
    // resolver-side `navgrid.walkable(cx, cz)` lowers to a call into
    // `navgrid_walkable` (in `compose_namespace_prelude`), which
    // delegates to `voxel_navgrid_walkable` below.
    let needs_navgrid_helpers = body.contains("voxel_navgrid_walkable(")
        || prelude.contains("voxel_navgrid_walkable(");
    if needs_navgrid_helpers {
        out.push_str(NAVGRID_WGSL_PRELUDE);
        out.push('\n');
    }

    // PerCell topologies (today only the tiled-MoveBoid kernel)
    // need module-level `var<workgroup>` declarations for the
    // cooperative tile arrays — they're shared across all lanes of
    // the workgroup but addressed per-lane inside the kernel body.
    // Sized for a 27-cell × MAX_PER_CELL neighborhood (= 864 entries
    // for boids' defaults). The kernel preamble + per-fold inner
    // walk both reference these symbols by name (`tile_pos`,
    // `tile_vel`, `tile_count`); emitting the decls here keeps them
    // alongside the matching `@compute @workgroup_size` header
    // without smuggling a `var<workgroup>` mid-body (illegal in WGSL).
    let dispatch_shape = topology_dispatch_shape(topology);
    let is_per_cell = matches!(dispatch_shape, DispatchShape::PerCell);
    let is_per_scan_chunk = matches!(dispatch_shape, DispatchShape::PerScanChunk);
    if is_per_scan_chunk {
        // PerScanChunk topologies (parallel prefix-scan kernels)
        // share a 256-entry workgroup-local buffer holding the
        // Hillis-Steele scan working set. Sized to match
        // `PER_SCAN_CHUNK_WORKGROUP_X` so every lane has exactly
        // one slot — keep the constant in sync if the chunk size
        // is ever bumped.
        let chunk = crate::cg::dispatch::PER_SCAN_CHUNK_WORKGROUP_X;
        out.push_str(&format!(
            "// Workgroup-local scratch for the Hillis-Steele scan.\n\
             // One u32 per lane; total = {chunk} × 4 = {bytes} B.\n\
             var<workgroup> scan_shared: array<u32, {chunk}>;\n\n",
            chunk = chunk,
            bytes = chunk * 4,
        ));
    }
    if is_per_cell {
        // The tile-array size derives from `MAX_PER_CELL` so a knob
        // change in `crate::cg::emit::spatial` flows through here
        // without a separate edit. The 27 stays a literal — it's a
        // structural property of "3³ neighborhood" the tile-walk emit
        // hardcodes too, and surfacing it as a constant would just
        // make both sites read the same magic number.
        let max_per_cell = super::spatial::MAX_PER_CELL;
        let total_slots = 27 * max_per_cell;
        out.push_str(&format!(
            "// Workgroup-local tile arrays for the 27-cell neighborhood.\n\
             // Sized for SPATIAL_MAX_PER_CELL (= {max}) slots per cell × 27\n\
             // cells = {total} entries each. tile_count holds the per-cell\n\
             // population; tile_pos/tile_vel mirror the agent fields the\n\
             // body's projections read via per_pair_candidate.\n\
             var<workgroup> tile_count: array<u32, 27>;\n\
             var<workgroup> tile_pos: array<vec3<f32>, 27 * {max}>;\n\
             var<workgroup> tile_vel: array<vec3<f32>, 27 * {max}>;\n\n",
            max = max_per_cell,
            total = total_slots,
        ));
    }

    let workgroup = topology_workgroup_size(topology);
    // 2-D dispatches (today: only PerAgentEventScan) declare both
    // `(x, y)` on the @workgroup_size annotation; 1-D shapes drop the
    // y-dim so the WGSL stays unchanged for every existing kernel.
    // Sequential per-event kernels override to @workgroup_size(1): a
    // single thread walks the whole event ring, eliminating the CAS
    // race between threads competing on the same target agent.
    // PERF (2026-09-03): the spatial scatter is a OneShot dispatch (one
    // workgroup) whose body cooperates across 256 threads; see
    // `SPATIAL_BUILD_HASH_SCATTER_BODY`.
    let is_wide_scatter = spec.name.ends_with("build_hash_scatter");
    let workgroup_attr = if is_wide_scatter {
        "@workgroup_size(256)".to_string()
    } else if sequential_per_event {
        "@workgroup_size(1)".to_string()
    } else if workgroup.y > 1 {
        format!("@workgroup_size({}, {})", workgroup.x, workgroup.y)
    } else {
        format!("@workgroup_size({})", workgroup.x)
    };

    if is_per_cell || is_per_scan_chunk {
        // PerCell + PerScanChunk entry points: take `workgroup_id`
        // + `local_invocation_id` instead of the usual
        // `global_invocation_id`. The body's per-shape preamble
        // (PerCell: `tiled_per_cell_preamble`; PerScanChunk:
        // `thread_indexing_preamble`) reads these to derive its
        // working indices.
        out.push_str(&format!(
            "@compute {workgroup_attr}\n\
             fn {entry}(\n\
             \x20   @builtin(workgroup_id) workgroup_id: vec3<u32>,\n\
             \x20   @builtin(local_invocation_id) local_invocation_id: vec3<u32>,\n\
             ) {{\n",
            entry = spec.entry_point
        ));
    } else {
        out.push_str(&format!(
            "@compute {workgroup_attr}\n\
             fn {entry}(@builtin(global_invocation_id) gid: vec3<u32>) {{\n",
            entry = spec.entry_point
        ));
    }

    // Sequential per-event: replace the parallel `gid.x`-indexed
    // preamble with a single-thread guard + sequential loop.  The
    // original preamble is:
    //   let event_idx = gid.x;\n
    //   if (event_idx >= cfg.event_count) { return; }\n
    // We replace the first line with the OneShot guard + loop header;
    // the second line (bounds check) becomes unnecessary (the loop
    // condition covers it) and is dropped by the replacement.
    if sequential_per_event {
        const PREAMBLE_GID: &str = "let event_idx = gid.x;\n";
        const PREAMBLE_BOUNDS: &str = "if (event_idx >= cfg.event_count) { return; }\n";
        let sequential_body = body
            .replacen(PREAMBLE_GID, "if (gid.x != 0u) { return; }\nfor (var event_idx = 0u; event_idx < cfg.event_count; event_idx = event_idx + 1u) {\n", 1)
            .replacen(PREAMBLE_BOUNDS, "", 1);
        out.push_str(&sequential_body);
        if !sequential_body.ends_with('\n') {
            out.push('\n');
        }
        // Close the sequential for-loop before the function's closing `}`.
        out.push_str("}\n");
    } else {
        out.push_str(body);
        if !body.ends_with('\n') {
            out.push('\n');
        }
    }
    out.push_str("}\n");

    out
}

/// Threads covered by ONE full-width row of a **wide 1-D dispatch**.
///
/// `max_compute_workgroups_per_dimension` is 65535 (the WebGPU spec
/// minimum, and exactly what every device in this corpus reports), so a
/// single-axis `dispatch_workgroups(n, 1, 1)` tops out at
/// `65535 x 64 = 4_194_240` threads. The pair-keyed domains
/// (`agent_cap^2` — belief fold/decay storage and PerPair fused masks)
/// pass that at **agent_cap 2048** (`2048^2 / 64 = 65_536` workgroups,
/// one over the limit) and wgpu kills the process with a validation
/// error rather than clamping.
///
/// The fix is a chunked dispatch expressed as full-width rows: emit
/// `dispatch_workgroups(65535, ceil(wg / 65535), 1)` and have the WGSL
/// preamble reconstruct the flat index as
/// `gid.y * WIDE_DISPATCH_ROW_THREADS + gid.x`. Because every row is
/// EXACTLY this wide, the reconstruction needs no uniform (no free cfg
/// slot exists on the ViewFold layout) and no host-side loop.
///
/// Determinism is untouched: each thread still owns exactly one slot,
/// the serial-scan folds still walk the radix-sorted ring in ring
/// order, and rows past the domain early-return on the same bounds
/// guard as before. Sub-4M domains emit `(wg, 1, 1)` exactly as they
/// did — `gid.y` is 0 there, so the added term is a no-op and existing
/// digests cannot move.
pub(crate) const WIDE_DISPATCH_ROW_THREADS: u32 = 65_535 * 64;

/// WGSL fragment reconstructing a wide 1-D dispatch's flat thread index
/// (see [`WIDE_DISPATCH_ROW_THREADS`]). Appended to every generated
/// preamble whose `gid.x` is a flat index into a domain that can be
/// chunked into y rows.
pub(crate) fn wide_index_term() -> String {
    format!(" + gid.y * {WIDE_DISPATCH_ROW_THREADS}u")
}

/// Emit the `pass.dispatch_workgroups(...)` lines for a wide 1-D
/// domain of `count_expr` threads at workgroup_size.x = 64.
/// See [`WIDE_DISPATCH_ROW_THREADS`] for why and for the determinism
/// argument.
fn compose_wide_1d_dispatch(count_expr: &str) -> String {
    format!(
        "        // Wide 1-D dispatch — `max_compute_workgroups_per_dimension`\n        \
         // is 65535, so domains past {WIDE_DISPATCH_ROW_THREADS} threads (the\n        \
         // agent_cap^2 pair map at cap >= 2048) are folded into FULL-WIDTH y\n        \
         // rows; the WGSL preamble rebuilds the flat index as\n        \
         // `gid.y * {WIDE_DISPATCH_ROW_THREADS}u + gid.x`. One row => identical\n        \
         // to the historical single-axis dispatch.\n        \
         let __wide_wg = ({count_expr} + 63u32) / 64u32;\n        \
         let (__wide_x, __wide_y) = if __wide_wg <= 65535u32 {{\n            \
         (__wide_wg, 1u32)\n        \
         }} else {{\n            \
         (65535u32, (__wide_wg + 65534u32) / 65535u32)\n        \
         }};\n        \
         pass.dispatch_workgroups(__wide_x, __wide_y, 1);\n"
    )
}

/// Pull the dispatch shape off a topology — handles all variants by
/// returning the per-stage shape stored on the topology. Used by
/// `compose_wgsl_file` to switch between the standard
/// `global_invocation_id` entry point and the PerCell
/// `(workgroup_id, local_invocation_id)` form.
fn topology_dispatch_shape(topology: &KernelTopology) -> DispatchShape {
    match topology {
        KernelTopology::Fused { dispatch, .. } => *dispatch,
        KernelTopology::Split { dispatch, .. } => *dispatch,
        KernelTopology::Indirect { .. } => DispatchShape::PerEvent {
            source_ring: crate::cg::data_handle::EventRingId(0),
        },
    }
}

/// Walk the kernel `body` for substrings naming registered namespace-
/// method WGSL function names; emit the matching B1-stub prelude
/// declarations in registry order. Returns an empty string when no
/// method is referenced.
///
/// The substring scan looks for `<wgsl_fn_name>(` (function call
/// syntax) so a comment that incidentally names the function doesn't
/// trigger a stub declaration. Order is iteration order over the
/// namespace registry's `BTreeMap`s — deterministic across runs.
fn compose_namespace_prelude(body: &str, prog: &CgProgram) -> String {
    let mut out = String::new();
    for ns_def in prog.namespace_registry.namespaces.values() {
        for method_def in ns_def.methods.values() {
            let needle = format!("{}(", method_def.wgsl_fn_name);
            if body.contains(&needle) {
                out.push_str(&method_def.wgsl_stub);
                out.push('\n');
            }
        }
    }
    out
}

/// Plan G G3f-deep (audit task #288) — view-storage helper prelude.
///
/// Emits a `fn view_<id>_get(idx: u32) -> f32 { ... }` helper for
/// every `view_<id>_get(` substring found in the kernel body. Mirrors
/// the per-view BGL binding `view_storage_<view_name>_primary` that
/// `kernel_topology_to_spec_and_body` appends to the kernel's spec
/// when the same substring is detected.
///
/// MVP scope: per-agent scalar f32 views only (the dodger fixture's
/// shape — `view threats(observer: Agent) -> f32`). Struct-payload
/// or pair-keyed views need richer prelude shapes (per-cell walk,
/// pair-key composition); deferred to follow-ups that close
/// ThreatsNearest / ThreatsDirAwayFromNearest.
///
/// **Bitcast.** The view's primary storage is `array<u32>` at the
/// BGL level (matches the runtime's wgpu::Buffer with `usage:
/// STORAGE | COPY_SRC | COPY_DST`); the f32 values are bitcast to
/// u32 at write time (`view_storage_primary[idx] = bitcast<u32>(value)`)
/// and bitcast back at read time. This is the standard scalar-view
/// storage convention.
/// Plan H slice 3 — emit `ability_registry_telegraph_*_at(id)` helper
/// fns when the kernel body references them. Sibling of
/// [`compose_view_storage_prelude`] but for ability-registry indexed
/// reads (per-ability scalars, single-arg lookup against the
/// `PackedAbilityRegistryGpu` SoA columns).
///
/// The substring scan + helper-emit shape mirrors the view-storage
/// pattern: detect `<helper>_at(` in the body, emit a bare
/// `fn <helper>_at(id: u32) -> <ty> { return <binding>[id]; }`. The
/// kernel body-scan in `cg/emit/kernel.rs` adds the matching
/// `ability_registry_telegraph_*` BGL binding when it sees the same
/// substring, so the helper's body resolves at WGSL compile time.
///
/// Stride-1 columns (`telegraph_kind`) read directly. Stride-N columns
/// (`telegraph_params` is 4×f32 per ability) compose `id * stride +
/// slot` inside the helper body — slot 0 hardcoded for the
/// `telegraph_param_0` flavour.
fn compose_ability_telegraph_prelude(body: &str) -> String {
    let mut out = String::new();
    // Ability ids in PackedAbilityRegistry are NonZero u32 starting at
    // 1 — id=0 is the empty-registry sentinel (no ability). The SoA
    // columns are 0-indexed Vec<u8|f32>, so the read at SoA index 0
    // corresponds to ability id 1. Compose `id - 1u` in each helper
    // so callers can pass `busy_with_ability_id` directly without
    // having to compute the offset themselves. Mirrors the existing
    // `interrupt_mask[busy_with_ability_id - 1]` convention used by
    // Plan G interrupt rules.
    //
    // Sentinel handling: when `id == 0` (no ability busy), the
    // subtraction underflows to `0xFFFFFFFFu` which would OOB-read.
    // Guard via `if (id == 0u) { return 0u; }` so the cell-write
    // surface gets a typed-zero (kind sentinel TELEGRAPH_KIND_NONE
    // for kind, 0.0 for params) instead of crashing the WGSL.
    if body.contains("ability_registry_telegraph_kind_at(") {
        out.push_str(
            "fn ability_registry_telegraph_kind_at(id: u32) -> u32 {\n\
             \x20   if (id == 0u) { return 0u; }\n\
             \x20   return ability_registry_telegraph_kind[id - 1u];\n\
             }\n",
        );
    }
    if body.contains("ability_registry_telegraph_param_0_at(") {
        // telegraph_params stride = 4 (4 × f32 per ability). Slot 0 is
        // the primary param (radius for Circle, width for Line). Future
        // _param_1 / _param_2 / _param_3 helpers stack on this same
        // shape with a different `+ N` offset.
        out.push_str(
            "fn ability_registry_telegraph_param_0_at(id: u32) -> f32 {\n\
             \x20   if (id == 0u) { return 0.0; }\n\
             \x20   return ability_registry_telegraph_params[(id - 1u) * 4u + 0u];\n\
             }\n",
        );
    }
    out
}

fn compose_view_storage_prelude(body: &str, prog: &CgProgram) -> String {
    use std::collections::{BTreeMap, BTreeSet};
    // Two parallel sets per view: which helpers are referenced. A view
    // that's only read via the scalar getter doesn't need the nearest
    // helper, and vice versa — emitting only what's referenced keeps
    // the kernel's WGSL surface minimal. `view_get_seen` covers both
    // legacy scalar `view_<id>_get(` and the ring-walk
    // `view_<id>_get(observer)` (same call site, different body).
    // `view_nearest_seen` covers the threats-only argmin reduction.
    let mut view_get_seen: BTreeSet<u32> = BTreeSet::new();
    let mut view_nearest_seen: BTreeSet<u32> = BTreeSet::new();
    let mut view_dir_seen: BTreeSet<u32> = BTreeSet::new();
    let mut search_pos = 0;
    while let Some(rel) = body[search_pos..].find("view_") {
        let abs = search_pos + rel;
        let after = &body[abs + 5..]; // skip "view_"
        let id_end = after.bytes().take_while(|b| b.is_ascii_digit()).count();
        if id_end > 0 {
            let suffix = &after[id_end..];
            // Order-sensitive prefix match — `_dir_away_from_nearest(`
            // shares its `_nearest(` infix with the bare argmin
            // helper, so we test the longer suffix first to avoid a
            // false positive on the nearest path.
            if suffix.starts_with("_dir_away_from_nearest(") {
                if let Ok(view_id) = after[..id_end].parse::<u32>() {
                    view_dir_seen.insert(view_id);
                }
            } else if suffix.starts_with("_get(") {
                if let Ok(view_id) = after[..id_end].parse::<u32>() {
                    view_get_seen.insert(view_id);
                }
            } else if suffix.starts_with("_nearest(") {
                if let Ok(view_id) = after[..id_end].parse::<u32>() {
                    view_nearest_seen.insert(view_id);
                }
            }
        }
        search_pos = abs + 5;
    }
    // Combined unique set drives the per-view metadata lookup loop.
    let mut seen_view_ids: BTreeSet<u32> = BTreeSet::new();
    seen_view_ids.extend(view_get_seen.iter().copied());
    seen_view_ids.extend(view_nearest_seen.iter().copied());
    seen_view_ids.extend(view_dir_seen.iter().copied());
    // A kernel that reads a `@per_entity_ring` struct field
    // (`view_<id>_field_<F>_get(`) but never calls the plain
    // `view_<id>_get(`/`_nearest(`/`_dir_away_from_nearest(` forms
    // leaves `seen_view_ids` empty — those three are the ONLY shapes
    // the scan above recognizes. Without this check the early return
    // below fires before the ring-field-read scan further down ever
    // runs, so a field-read-only kernel (e.g. `ring_field_read_probe`'s
    // `ReadBackCells`) silently gets no prelude at all: the call sites
    // and binding are correctly emitted elsewhere, but the helper
    // function definition itself never lands in the file, and naga
    // fails at pipeline creation with "no definition in scope."
    let has_ring_field_reads = {
        let mut sp = 0;
        let mut found = false;
        while let Some(rel) = body[sp..].find("view_") {
            let abs = sp + rel;
            let after = &body[abs + 5..];
            let id_end = after.bytes().take_while(|b| b.is_ascii_digit()).count();
            sp = abs + 5 + id_end.max(1);
            if id_end == 0 {
                continue;
            }
            let suffix = &after[id_end..];
            if let Some(after_field) = suffix.strip_prefix("_field_") {
                let fnum_len = after_field.bytes().take_while(u8::is_ascii_digit).count();
                if fnum_len > 0 && after_field[fnum_len..].starts_with("_get(") {
                    found = true;
                    break;
                }
            }
        }
        found
    };
    if seen_view_ids.is_empty() && !has_ring_field_reads {
        return String::new();
    }
    // Pre-resolve per-view shape so each helper-emit branch can
    // consult the same flags without re-walking program metadata.
    let mut shapes: BTreeMap<u32, (Option<u16>, bool)> = BTreeMap::new();
    for view_id in &seen_view_ids {
        let sig = prog.view_signatures.get(view_id);
        let layout = prog.view_layouts.get(view_id);
        let ring_k = sig.and_then(|s| match s.storage_hint {
            Some(super::super::program::CgStorageHint::PerEntityRing { k }) => Some(k),
            _ => None,
        });
        let is_threat_layout = layout
            .map(|l| {
                let names: Vec<&str> = l.fields.iter().map(|f| f.name.as_str()).collect();
                names == [
                    "zone_kind",
                    "center_x_q8",
                    "center_y_q8",
                    "radius_q8",
                    "dir_x_q8",
                    "dir_y_q8",
                    "expires_at_tick",
                    "source",
                ]
            })
            .unwrap_or(false);
        shapes.insert(*view_id, (ring_k, is_threat_layout));
    }
    let mut out = String::new();
    for view_id in &seen_view_ids {
        let view_name = prog
            .interner
            .get_view_name(crate::cg::data_handle::ViewId(*view_id))
            .unwrap_or("unnamed_view");
        // Branch on the view's storage shape:
        //   * scalar (the historical default): single-load + bitcast.
        //   * @per_entity_ring(K) + struct ViewLayout matching the
        //     8-field threat-zone schema: walk K cells, accumulate
        //     distance-weighted intensity at the observer's pos.
        //
        // The ring-walk path lets `threats.intensity_at(self)` actually
        // depend on (a) the observer's position and (b) the per-cell
        // zone center+radius+expiry, instead of returning a per-observer
        // scalar count of busy candidates. Required `agent_pos` /
        // `cfg.tick` bindings are added by the body-scan in
        // `cg/emit/kernel.rs` when it sees `view_<id>_get(` in a kernel
        // whose view has the threats schema.
        let (ring_k, is_threat_layout) =
            shapes.get(view_id).copied().unwrap_or((None, false));
        // `threats.dir_away_from_nearest(observer)` — same argmin
        // pass as the nearest helper, returns the unit vec3 pointing
        // AWAY from the closest cell's center. Lets a flee-style
        // score pick a movement direction directly. Emitted ONLY when
        // referenced AND the view carries the threat-zone struct
        // layout; sentinel stub otherwise.
        if view_dir_seen.contains(view_id) {
            if let (Some(k), true) = (ring_k, is_threat_layout) {
                let k = k as u32;
                out.push_str(&format!(
"fn view_{view_id}_dir_away_from_nearest(observer: u32) -> vec3<f32> {{
    let observer_pos = agent_pos[observer];
    var best_dist: f32 = 3.4028235e38;
    var best_dx: f32 = 0.0;
    var best_dy: f32 = 0.0;
    for (var c: u32 = 0u; c < {k}u; c = c + 1u) {{
        let base = (observer * {k}u + c) * 8u;
        let zone_kind = view_storage_{view_name}_primary[base + 0u];
        if (zone_kind == 0u) {{ continue; }}
        let expires = view_storage_{view_name}_primary[base + 6u];
        if (cfg.tick >= expires) {{ continue; }}
        let cx_raw = i32(view_storage_{view_name}_primary[base + 1u]);
        let cy_raw = i32(view_storage_{view_name}_primary[base + 2u]);
        let cx = f32((cx_raw << 16u) >> 16u) / 256.0;
        let cy = f32((cy_raw << 16u) >> 16u) / 256.0;
        let dx = observer_pos.x - cx;
        let dy = observer_pos.y - cy;
        let dist = sqrt(dx * dx + dy * dy);
        if (dist < best_dist) {{
            best_dist = dist;
            best_dx = dx;
            best_dy = dy;
        }}
    }}
    if (best_dist < 3.4028235e38 && best_dist > 0.0) {{
        return vec3<f32>(best_dx / best_dist, best_dy / best_dist, 0.0);
    }}
    return vec3<f32>(0.0, 0.0, 0.0);
}}
"
                ));
            } else {
                out.push_str(&format!(
                    "fn view_{view_id}_dir_away_from_nearest(_observer: u32) -> vec3<f32> {{ return vec3<f32>(0.0, 0.0, 0.0); }}\n"
                ));
            }
        }
        // `threats.nearest(observer)` — argmin reduction returning
        // the nearest live cell's `source` AgentId. Emitted ONLY when
        // a kernel body references `view_<id>_nearest(` AND the view
        // actually carries the threat-zone struct layout. The walk
        // mirrors the intensity getter: same per-cell live filter
        // (zone_kind != 0 AND world.tick < expires), same q8 → f32
        // unpack, but tracks `(min_dist, best_source)` instead of
        // accumulating intensity.
        if view_nearest_seen.contains(view_id) {
            if let (Some(k), true) = (ring_k, is_threat_layout) {
                let k = k as u32;
                out.push_str(&format!(
"fn view_{view_id}_nearest(observer: u32) -> u32 {{
    let observer_pos = agent_pos[observer];
    var best_dist: f32 = 3.4028235e38;
    var best_source: u32 = 0xFFFFFFFFu;
    for (var c: u32 = 0u; c < {k}u; c = c + 1u) {{
        let base = (observer * {k}u + c) * 8u;
        let zone_kind = view_storage_{view_name}_primary[base + 0u];
        if (zone_kind == 0u) {{ continue; }}
        let expires = view_storage_{view_name}_primary[base + 6u];
        if (cfg.tick >= expires) {{ continue; }}
        let cx_raw = i32(view_storage_{view_name}_primary[base + 1u]);
        let cy_raw = i32(view_storage_{view_name}_primary[base + 2u]);
        let cx = f32((cx_raw << 16u) >> 16u) / 256.0;
        let cy = f32((cy_raw << 16u) >> 16u) / 256.0;
        let dx = observer_pos.x - cx;
        let dy = observer_pos.y - cy;
        let dist = sqrt(dx * dx + dy * dy);
        if (dist < best_dist) {{
            best_dist = dist;
            best_source = view_storage_{view_name}_primary[base + 7u];
        }}
    }}
    return best_source;
}}
"
                ));
            } else {
                // Sentinel — caller already had a graceful fallback at
                // lowering time, but emitting a stub avoids a missing-
                // function naga error if some future call path reaches
                // here without the lowering's view-shape gate.
                out.push_str(&format!(
                    "fn view_{view_id}_nearest(_observer: u32) -> u32 {{ return 0xFFFFFFFFu; }}\n"
                ));
            }
        }
        // Skip the scalar/intensity helper if this view was only
        // referenced via `view_<id>_nearest(` — emitting it
        // unnecessarily would add an unused function and pull in the
        // agent_pos binding (when ring-walk) for kernels that don't
        // need it.
        if !view_get_seen.contains(view_id) {
            continue;
        }
        if let (Some(k), true) = (ring_k, is_threat_layout) {
            let k = k as u32;
            // q8 fixed-point conversion: i16 packed in low 16 bits of
            // the u32 slot. Sign-extend with `<< 16 >> 16`, then
            // divide by 256.0 to recover the f32. radius_q8 is a u16
            // (always positive) so no sign extension needed.
            out.push_str(&format!(
"fn view_{view_id}_get(observer: u32) -> f32 {{
    let observer_pos = agent_pos[observer];
    var sum: f32 = 0.0;
    for (var c: u32 = 0u; c < {k}u; c = c + 1u) {{
        let base = (observer * {k}u + c) * 8u;
        let zone_kind = view_storage_{view_name}_primary[base + 0u];
        if (zone_kind == 0u) {{ continue; }}
        let expires = view_storage_{view_name}_primary[base + 6u];
        if (cfg.tick >= expires) {{ continue; }}
        let cx_raw = i32(view_storage_{view_name}_primary[base + 1u]);
        let cy_raw = i32(view_storage_{view_name}_primary[base + 2u]);
        let cx = f32((cx_raw << 16u) >> 16u) / 256.0;
        let cy = f32((cy_raw << 16u) >> 16u) / 256.0;
        let radius = f32(view_storage_{view_name}_primary[base + 3u]) / 256.0;
        let dx = observer_pos.x - cx;
        let dy = observer_pos.y - cy;
        let dist = sqrt(dx * dx + dy * dy);
        if (dist < radius) {{
            sum = sum + (radius - dist);
        }}
    }}
    return sum;
}}
"
            ));
        } else {
            // Plan I slice I.3b extension — pair-keyed view-read.
            // When the view's signature has 2 params (the lowering
            // for `views.<name>(observer, key)` emits 2-arg form)
            // and the second key has a static K, emit a 2-arg
            // helper that composes the `observer * K + key` index.
            // Untyped result currently returns u32 directly (no
            // bitcast — pair-keyed beliefs are u32-typed in every
            // shipping fixture). Future cuts may need an f32 variant.
            //
            // Single-arg single-key (Threats scalar) path is the
            // historical default fall-through below.
            let sig = prog.view_signatures.get(view_id);
            let is_pair_keyed_2arg = sig
                .map(|s| s.args.len() == 2)
                .unwrap_or(false);
            let pair_k = sig.and_then(|s| s.pair_keyed_k);
            if is_pair_keyed_2arg {
                // 2-arg pair-keyed accessor. The row stride between observers
                // is the second-key population: a STATIC K for `@key_pop`
                // belief pairs (u32-typed), or the RUNTIME agent_count for
                // Agent×Agent `pair_map` views (f32-typed). The fold/decay
                // WRITE side composes `local_a * cfg.second_key_pop + local_b`
                // (`cg/emit/wgsl_body.rs`), and `build_helper` sets that
                // ViewFold `cfg.second_key_pop = self.agent_count` for the
                // Agent case — which equals this (generic/per-agent) reading
                // kernel's `cfg.agent_cap` (also `self.agent_count`). We index
                // with `cfg.agent_cap` here because the reading kernel's cfg
                // struct is `{ agent_cap, tick, seed, _pad }` and has no
                // `second_key_pop` field. Before this, a dynamic-K view
                // (`pair_k == None`) fell through to the 1-arg scalar form
                // below while its call site passed 2 args → `ArgumentCount`
                // invalid WGSL (the predator_prey `predator_focus(self,
                // target)` failure).
                match pair_k {
                    Some(k) => out.push_str(&format!(
                        "fn view_{view_id}_get(observer: u32, key: u32) -> u32 {{\n\
                         \x20   return view_storage_{view_name}_primary[observer * {k}u + key];\n\
                         }}\n"
                    )),
                    None => {
                        // Dynamic-K (Agent×Agent): stride is `cfg.agent_cap`
                        // (= agent_count). Respect the view's result type —
                        // f32 views (e.g. predator_focus, a decaying float
                        // tally) bitcast from the u32 storage cell; u32 views
                        // return the cell directly.
                        let result_is_f32 = sig
                            .map(|s| matches!(s.result, crate::cg::expr::CgTy::F32))
                            .unwrap_or(false);
                        if result_is_f32 {
                            out.push_str(&format!(
                                "fn view_{view_id}_get(observer: u32, key: u32) -> f32 {{\n\
                                 \x20   return bitcast<f32>(view_storage_{view_name}_primary[observer * cfg.agent_cap + key]);\n\
                                 }}\n"
                            ));
                        } else {
                            out.push_str(&format!(
                                "fn view_{view_id}_get(observer: u32, key: u32) -> u32 {{\n\
                                 \x20   return view_storage_{view_name}_primary[observer * cfg.agent_cap + key];\n\
                                 }}\n"
                            ));
                        }
                    }
                }
            } else {
                // Scalar getter — read u32 from the storage binding,
                // bitcast to f32. The binding name + slot are pinned
                // by `kernel_topology_to_spec_and_body`'s body-scan
                // step which appends `view_storage_<view_name>_primary`
                // to the kernel's BGL when the same substring is
                // detected.
                out.push_str(&format!(
                    "fn view_{view_id}_get(idx: u32) -> f32 {{\n\
                     \x20   return bitcast<f32>(view_storage_{view_name}_primary[idx]);\n\
                     }}\n"
                ));
            }
        }
    }

    // Read side of `@per_entity_ring` struct-payload storage
    // (`BuiltinId::RingFieldRead`, `<ring_view_name>.<field>(key,
    // index)`). Independent scan from the per-view loop above: one
    // helper per (view, field) pair actually referenced, not one per
    // view — a struct cell can have several fields, each read
    // separately and each needing its own function since WGSL has no
    // generic "return the Nth word as the right type" primitive.
    {
        let mut seen: BTreeSet<(u32, u16)> = BTreeSet::new();
        let mut search_pos = 0;
        while let Some(rel) = body[search_pos..].find("view_") {
            let abs = search_pos + rel;
            let after = &body[abs + 5..];
            let id_end = after.bytes().take_while(|b| b.is_ascii_digit()).count();
            search_pos = abs + 5 + id_end.max(1);
            if id_end == 0 {
                continue;
            }
            let suffix = &after[id_end..];
            let Some(after_field) = suffix.strip_prefix("_field_") else { continue };
            let fnum_len = after_field.bytes().take_while(u8::is_ascii_digit).count();
            if fnum_len == 0 || !after_field[fnum_len..].starts_with("_get(") {
                continue;
            }
            let (Ok(view_id), Ok(field_offset)) =
                (after[..id_end].parse::<u32>(), after_field[..fnum_len].parse::<u16>())
            else {
                continue;
            };
            if !seen.insert((view_id, field_offset)) {
                continue;
            }
            let view_name = prog
                .interner
                .get_view_name(crate::cg::data_handle::ViewId(view_id))
                .unwrap_or("unnamed_view");
            let sig = prog.view_signatures.get(&view_id);
            let k = sig.and_then(|s| match s.storage_hint {
                Some(crate::cg::program::CgStorageHint::PerEntityRing { k }) => Some(k as u32),
                _ => None,
            });
            let layout = prog.view_layouts.get(&view_id);
            let field_count = layout.map(|l| l.fields.len() as u32).unwrap_or(1);
            let field_ty = layout.and_then(|l| l.fields.get(field_offset as usize)).map(|f| f.ty);
            // `k`/`layout` absent means the source didn't actually
            // satisfy `RingFieldRead`'s lowering-time gate — lowering
            // already rejects that (`RingFieldReadRequiresPerEntityRing`
            // / `RingFieldReadOnScalarRing`), so reaching here with
            // either missing would mean a caller built CG by hand
            // bypassing `lower_ring_field_read`. Default to a k=1,
            // u32 shape rather than panicking mid-emit — matches this
            // file's existing "sentinel, not a hard failure" convention
            // for defensive fallbacks (see the `view_{id}_nearest`
            // sentinel stub above).
            let k = k.unwrap_or(1);
            let is_f32 = matches!(field_ty, Some(crate::cg::expr::CgTy::F32));
            let ret_ty = if is_f32 { "f32" } else { "u32" };
            let read_expr = format!(
                "view_storage_{view_name}_primary[(key * {k}u + (index % {k}u)) * {field_count}u + {field_offset}u]"
            );
            let body_expr = if is_f32 { format!("bitcast<f32>({read_expr})") } else { read_expr };
            out.push_str(&format!(
                "fn view_{view_id}_field_{field_offset}_get(key: u32, index: u32) -> {ret_ty} {{\n\
                 \x20   return {body_expr};\n\
                 }}\n"
            ));
        }
    }

    out
}

/// Emit the WGSL `struct {Pascal}Cfg { ... };` declaration kernels
/// reference from the cfg uniform binding. Sourced from the cfg
/// binding's WGSL type name; field shape branches on
/// [`KernelKind`] to mirror the Rust [`KernelSpec::cfg_struct_decl`]:
///   - `ViewFold`: `{ event_count, tick, second_key_pop, agent_cap }`
///   - `Generic`:  `{ agent_cap, tick, seed, _pad }`
///
/// # Limitations
///
/// - **Field shape is hard-coded per `KernelKind`.** As more kernel
///   kinds land with bespoke cfgs (per-kind refinements anticipated by
///   `build_generic_cfg_struct_decl`'s comment), the right move is to
///   surface a `cfg_wgsl_decl` field from the kernel-spec layer rather
///   than branching here.
fn compose_wgsl_cfg_struct(spec: &KernelSpec) -> String {
    let cfg = spec
        .bindings
        .iter()
        .find(|b| matches!(b.bg_source, BgSource::Cfg))
        .expect("KernelSpec must carry a cfg binding");
    // Generic-kernel cfg gained `tick: u32` when PerAgent rules with
    // `emit <Event>` bodies started writing the tick header word into
    // the event ring. Layout matches `build_generic_cfg_struct_decl`
    // (Rust side): { agent_cap: u32, tick: u32, _pad0: u32, _pad1: u32 }.
    let base_fields = match spec.kind {
        // `second_key_pop` joined the layout with the pair_map storage
        // gap fix (2026-05-03): fold body's RMW indexes
        // `view_storage_primary[k1 * cfg.second_key_pop + k2]` for
        // 2-D views; single-key views set the field to 1 so the index
        // reduces to `k_last`. Mirrors the Rust `FoldXxxCfg` struct
        // (build_view_fold_cfg_struct_decl).
        KernelKind::ViewFold => "event_count: u32, tick: u32, second_key_pop: u32, agent_cap: u32",
        // `slot_count` joined the layout in lockstep — pair_map views
        // over-allocate `agent_cap × second_pop` slots; the decay
        // kernel iterates `slot_count` instead of `agent_cap` so the
        // anchor multiplier reaches every (k1, k2). Single-key views
        // set `slot_count == agent_cap`. Mirrors
        // build_view_decay_cfg_struct_decl.
        KernelKind::ViewDecay => "agent_cap: u32, tick: u32, slot_count: u32, _pad0: u32",
        // PerEventEmit (PerEvent-dispatched physics rule with `Emit`
        // body) mirrors ViewFold's `event_count + tick` layout: the
        // body's `if event_idx >= cfg.event_count { return; }`
        // guard needs the per-tick event count from the runtime, and
        // the `Emit` writes still need `tick` for the event header
        // word. `seed: u32` joined when the rng.* surface wired
        // through (stochastic_probe Gaps #1-#3 close, 2026-05-04).
        // `agent_cap: u32` joined in Wave 3 ToM Phase 3.7 so the
        // belief-setter WGSL stubs can index columns as
        // `cell = observer * cfg.agent_cap + subject`.
        // Mirrors `build_per_event_emit_cfg_struct_decl`.
        KernelKind::PerEventEmit => "event_count: u32, tick: u32, seed: u32, agent_cap: u32",
        // Generic kernels (physics/mask/plumbing) carry `seed: u32`
        // so the kernel preamble can bind `let seed = cfg.seed;` for
        // any `per_agent_u32(seed, agent_id, tick, purpose)` call the
        // body lowers from `rng.*`. Mirrors `build_generic_cfg_struct_decl`.
        KernelKind::Generic => "agent_cap: u32, tick: u32, seed: u32, _pad0: u32",
    };
    // Plan G tunable cfg — append every runtime-tunable cfg field the
    // kernel referenced (mirrors the Rust struct decl in
    // `kernel.rs::build_generic_cfg_struct_decl` /
    // `build_per_event_emit_cfg_struct_decl`). One `, <name>: <ty>`
    // entry per field, in `ConfigConstId`-ascending order. ViewFold /
    // ViewDecay never carry runtime fields today so the suffix stays
    // empty for those branches; the Generic + PerEventEmit branches
    // surface the kernel-specific knob set.
    let mut fields = base_fields.to_string();
    for (name, ty) in &spec.runtime_cfg_fields {
        fields.push_str(", ");
        fields.push_str(name);
        fields.push_str(": ");
        fields.push_str(ty);
    }
    format!("struct {ty} {{ {fields} }};\n", ty = cfg.wgsl_ty)
}

/// Compose a single `.rs` file from a [`KernelSpec`] + originating
/// [`KernelTopology`] (used to derive the dispatch-workgroup expression
/// inside the [`crate::Kernel::record`] body).
///
/// The output mirrors the legacy Rust kernel modules' shape (see
/// `crates/engine_gpu_rules/src/alive_pack.rs` for a template), with
/// the differences documented in the module-level `# Limitations`. Each
/// section is sourced from one of the [`crate::kernel_lowerings`]
/// helpers, so a regression in any single emitted form is caught by the
/// lowering's own tests; this composer is structural glue only.
///
/// The synthesized module is `crate::Kernel`-implementing: the
/// `<Pascal>Kernel` struct, `<Pascal>Bindings<'a>`, the cfg struct, an
/// `impl crate::Kernel for <Pascal>Kernel { … }` block (real bodies,
/// no panics), and the standalone helper fns (`<name>_bgl_entries`,
/// `<name>_bind_group_entries`, `<name>_build_cfg`) the legacy callers
/// expect.
///
/// # Limitations
/// - The `record()` body uses
///   `pass.dispatch_workgroups((agent_cap + N - 1) / N, 1, 1)` for
///   per-agent / per-event / per-pair / per-word kernels, and
///   `(1, 1, 1)` for one-shot. Indirect dispatch
///   (`dispatch_workgroups_indirect`) is a Task 5.4+ concern — the
///   legacy emitters today use the same agent-cap-bounded direct
///   dispatch as a placeholder for per-event kernels.
/// - The `bind()` body is built from the spec's [`BgSource`] tags via
///   [`render_bg_source_expr`]; ViewHandle / AliasOf are routed
///   through `unwrap_or(primary)` patterns that mirror the legacy fold
///   kernels' pattern. None of today's CG kernels emit those variants
///   (Task 5.4+ wires fold-view tuple destructuring); the helpers stay
///   in place defensively so the composer never panics.
fn compose_rust_module_file(spec: &KernelSpec, topology: &KernelTopology, sequential_per_event: bool) -> String {
    let mut out = String::new();
    out.push_str("// GENERATED by dsl_compiler — do not edit by hand.\n");
    out.push_str("// Regenerated by each runtime crate's build.rs on cargo check / build.\n");
    out.push('\n');

    // Phase 7 boids GPU pipeline (2026-05-02): kernel modules now
    // target `engine::gpu::Kernel` (hand-written platform trait) and
    // construct `Bindings` directly with explicit `&wgpu::Buffer`
    // refs. The deleted `bind()` method took a `&BindingSources`
    // aggregate that the wolf-sim runtime owned; per-fixture
    // runtimes now wire bindings inline at the dispatch call site.

    // Per-kernel struct (carries the pipeline + BGL).
    out.push_str(&format!(
        "pub struct {pascal}Kernel {{\n    \
         pipeline: wgpu::ComputePipeline,\n    \
         bgl: wgpu::BindGroupLayout,\n    \
         /// PERF (2026-09-03): the bind group, cached across ticks. `record()` used\n    \
         /// to call `create_bind_group` every dispatch every tick — ~136 per tick\n    \
         /// on a colony-sized fixture, a flat host cost that never shrank with\n    \
         /// agent count. The bindings are the same buffer handles tick after\n    \
         /// tick (uniforms are updated with `write_buffer`, never re-created),\n    \
         /// so the group is rebuilt only when a buffer handle actually changes.\n    \
         /// Presentation of the same descriptor to the same layout: identical\n    \
         /// GPU work, so digests cannot move.\n    \
         bg_cache: std::cell::RefCell<Option<(Vec<(wgpu::Buffer, u64, u64)>, wgpu::BindGroup)>>,\n}}\n\n",
        pascal = spec.pascal
    ));

    // Bindings struct. ViewFold kernels emit `Option<&'a wgpu::Buffer>`
    // for the anchor/ids slots (matching the legacy fold-kernel
    // contract); generic kernels use the spec-driven lowering which
    // emits `&'a wgpu::Buffer` for every binding.
    out.push_str(&format!(
        "pub struct {pascal}Bindings<'a> {{\n",
        pascal = spec.pascal
    ));
    if matches!(spec.kind, KernelKind::ViewFold) {
        out.push_str(&compose_view_fold_bindings_struct_fields(spec));
    } else {
        out.push_str(&lower_rust_bindings_struct_fields(spec));
    }
    out.push_str("}\n\n");

    // ViewFold kernels skip the constructor — their custom
    // anchor/ids/sim_cfg shape doesn't fit the standard naming
    // convention; per-fixture runtimes construct them via the existing
    // `view_storage` helpers.
    if !matches!(spec.kind, KernelKind::ViewFold) {
        out.push_str(&compose_bindings_from_context(spec));
    }

    // Cfg struct decl — KernelSpec.cfg_struct_decl is the full
    // `#[repr(C)] ... pub struct <Cfg> { ... }` form.
    out.push_str(&spec.cfg_struct_decl);
    out.push_str("\n\n");

    // WGSL source — the `.wgsl` file is co-located in the output
    // directory; `include_str!` resolves it at compile time when the
    // emitted crate is built.
    out.push_str(&format!(
        "const SHADER_SRC: &str = include_str!(\"{name}.wgsl\");\n\n",
        name = spec.name
    ));

    // Kernel trait impl.
    out.push_str(&compose_kernel_trait_impl(spec, topology, sequential_per_event));
    out.push('\n');

    // BGL entries function. ViewFold kernels skip the standalone
    // `_bgl_entries` / `_bind_group_entries` / `_build_cfg` helpers —
    // the legacy `crates/engine_gpu_rules/src/fold_<view>.rs` modules
    // do not expose them, and the `lower_rust_bg_entries` lowering
    // would produce `Option`-typed expressions that don't carry
    // `.as_entire_binding()`. The Kernel trait impl above remains the
    // single entry point for ViewFold callers.
    if !matches!(spec.kind, KernelKind::ViewFold) {
        out.push_str(&format!(
            "pub fn {name}_bgl_entries() -> Vec<wgpu::BindGroupLayoutEntry> {{\n    \
             vec![\n",
            name = spec.name
        ));
        out.push_str(&render_cg_bgl_entries(spec));
        out.push_str("    ]\n}\n\n");

        // Bind-group entries function. Returns the BindGroupEntry list a
        // caller wraps with the BGL into a BindGroup.
        out.push_str(&format!(
            "pub fn {name}_bind_group_entries<'a>(\n    \
             bindings: &'a {pascal}Bindings<'a>,\n) -> \
             Vec<wgpu::BindGroupEntry<'a>> {{\n    vec![\n",
            name = spec.name,
            pascal = spec.pascal
        ));
        out.push_str(&lower_rust_bg_entries(spec));
        out.push_str("    ]\n}\n\n");

        // Phase 7 boids GPU pipeline (2026-05-02): dropped the
        // `<name>_build_cfg(state: &engine::state::SimState)` standalone
        // helper. The cfg shape (`<Pascal>Cfg`) is `#[repr(C)]` POD;
        // per-fixture runtimes construct it directly with primitive
        // args at the dispatch call site (e.g.,
        // `PhysicsMoveBoidCfg { agent_cap: 16, _pad: [0; 3] }`).
    }

    out
}

/// Classify an emitted Bindings field by name → which shared source
/// the compiler-emitted `from_context()` constructor pulls it from.
///
/// The naming convention (kept in sync with the
/// `engine::gpu::bindings_context` module docs):
///
/// | Field name pattern              | Classification                    |
/// |---------------------------------|-----------------------------------|
/// | `event_ring`                    | `BindingSource::EventRingRing`    |
/// | `event_tail`                    | `BindingSource::EventRingTail`    |
/// | `agent_<col>` where col is in   | `BindingSource::AgentBuffer(col)` |
/// |   `engine::gpu::AgentBuffers::STANDARD_COLUMNS` |                  |
/// | `ability_registry_<col>`        | `BindingSource::Registry(col)`    |
/// | `voxel_grid` (Phase C)          | `BindingSource::VoxelGrid`        |
/// | `cfg`                           | `BindingSource::Cfg`              |
/// | (anything else)                 | `BindingSource::Extras`           |
///
/// The "anything else" bucket catches fixture-specific buffers — mask
/// bitmaps, scoring output, fixture-specific SoA columns (e.g.,
/// `agent_creature_type` in spy_network) — which ride a per-kernel
/// `<Pascal>Extras` struct passed to `from_context_with_extras`.
#[derive(Debug, Clone, PartialEq, Eq)]
enum BindingSource<'a> {
    EventRingRing,
    EventRingTail,
    AgentBuffer(&'a str),
    Registry(&'a str),
    /// Phase C — `voxel_grid` resolves to
    /// `ctx.voxel_grid.expect("kernel binds voxel_grid but the runtime
    /// didn't supply ctx.voxel_grid")`. Optional on the context so
    /// non-voxel fixtures don't pay the buffer alloc.
    VoxelGrid,
    /// Voxel-region-indices Phase 4b — `navgrid` resolves to
    /// `ctx.navgrid.expect(...)`. Storage buffer for the per-region
    /// navgrid index built by `engine_voxel::build_navgrid`.
    Navgrid,
    /// Phase 4b sibling — `navgrid_cfg` is a 4-u32 uniform
    /// `[size_x, size_z, origin_x, origin_z]` the WGSL helper reads
    /// to compute the cell index + bounds-check. Synthesised
    /// alongside `Navgrid` in the kernel substring scan; routed
    /// through `ctx.navgrid_cfg.expect(...)`.
    NavgridCfg,
    Cfg,
    Extras,
}

/// The compiler's mirror of `engine::gpu::AgentBuffers::STANDARD_COLUMNS`.
